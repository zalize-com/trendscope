const esc = s => { const d = document.createElement("div"); d.textContent = s||""; return d.innerHTML; };
const $ = id => document.getElementById(id);
const params = new URLSearchParams(location.search);

function mdInline(s) {
  s = s.replace(/`([^`]+)`/g, (m, c) => `<code>${c}</code>`);
  s = s.replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>").replace(/__([^_]+)__/g, "<b>$1</b>");
  s = s.replace(/\*([^*\n]+)\*/g, "<i>$1</i>").replace(/\b_([^_\n]+)_/g, "<i>$1</i>");
  s = s.replace(/\[([^\]]+)\]\((https?:\/\/[^)\s]+|[^)\s]+)\)/g, '<a href="$2" target="_blank" rel="noopener">$1</a>');
  return s;
}
function mdRender(src) {
  const lines = src.split("\n");
  let html = "", inCode = false, list = null, para = [], tbl = null;
  const flushPara = () => { if (para.length) { html += `<p>${mdInline(para.join(" "))}</p>`; para = []; } };
  const flushList = () => { if (list) { html += `</${list}>`; list = null; } };
  const flushTbl = () => { if (tbl) { html += "</table>"; tbl = null; } };
  for (const raw of lines) {
    if (/^```/.test(raw)) {
      flushPara(); flushList(); flushTbl();
      html += inCode ? "</code></pre>" : "<pre><code>";
      inCode = !inCode; continue;
    }
    if (inCode) { html += esc(raw) + "\n"; continue; }
    const t = raw.trimEnd();
    if (!t.trim()) { flushPara(); flushList(); flushTbl(); continue; }
    if (/^\|.+\|$/.test(t)) {
      flushPara(); flushList();
      const cells = t.split("|").slice(1, -1).map(c => c.trim());
      if (cells.every(c => /^:?-+:?$/.test(c))) continue;
      if (!tbl) { tbl = true; html += "<table>"; }
      html += "<tr>" + cells.map(c => `<td>${mdInline(esc(c))}</td>`).join("") + "</tr>";
      continue;
    }
    flushTbl();
    let m;
    if (m = t.match(/^(#{1,6})\s+(.*)/)) {
      flushPara(); flushList();
      const lv = Math.min(m[1].length, 3);
      html += `<h${lv}>${mdInline(esc(m[2]))}</h${lv}>`;
    } else if (/^(-{3,}|\*{3,})$/.test(t)) {
      flushPara(); flushList(); html += "<hr>";
    } else if (m = t.match(/^>|^&gt;/)) {
      flushPara(); flushList();
      html += `<blockquote>${mdInline(esc(t.replace(/^&gt;|^>\s?/, "")))}</blockquote>`;
    } else if (m = t.match(/^[-*+]\s+(.*)/)) {
      flushPara();
      if (list !== "ul") { flushList(); html += "<ul>"; list = "ul"; }
      html += `<li>${mdInline(esc(m[1]))}</li>`;
    } else if (m = t.match(/^\d+[.)]\s+(.*)/)) {
      flushPara();
      if (list !== "ol") { flushList(); html += "<ol>"; list = "ol"; }
      html += `<li>${mdInline(esc(m[1]))}</li>`;
    } else {
      flushList(); para.push(esc(t));
    }
  }
  flushPara(); flushList(); flushTbl();
  if (inCode) html += "</code></pre>";
  return html;
}

const idx = await fetch("docs/index.json", {cache:"no-cache"}).then(r => r.json()).catch(() => ({digests:[],movers:[],briefs:[]}));
const files = [
  ...(idx.digests || []).map(f => ({ f, dir: "digest" })),
  ...(idx.briefs || []).map(d => ({ f: d + ".md", dir: "brief" })),
];
if (!files.length) {
  $("doc").innerHTML = '<p id="err">No digests yet — the first weekly digest is generated by the daily pipeline.</p>';
} else {
  const wanted = params.get("w") || files[0].f;
  $("files").innerHTML = files.map(e =>
    `<button data-f="${e.f}" class="${e.f===wanted?"active":""}">${e.dir==="brief"?"📄 ":""}${e.f.replace(/\.md$/,"")}${e.f.includes("notes")?" ✍":""}</button>`).join("");
  let cur = wanted;
  let lastMd = "";
  const dirOf = f => (files.find(e => e.f === f) || {dir: "digest"}).dir;
  async function show(f) {
    cur = f;
    document.querySelectorAll("#files button").forEach(b => b.classList.toggle("active", b.dataset.f === f));
    history.replaceState(null, "", `?w=${encodeURIComponent(f)}`);
    const md = await fetch(`docs/${dirOf(f)}/${f}`, {cache:"no-cache"}).then(r => {
      if (!r.ok) throw new Error(String(r.status));
      return r.text();
    });
    lastMd = md;
    const i = files.findIndex(e => e.f === f);
    const nav = `<p style="font-size:12px;color:var(--dim);margin:0 0 12px">` +
      (i < files.length - 1 ? `<a href="#" data-nav="${files[i+1].f}">← ${files[i+1].f.replace(/\.md$/,"")}</a> ` : `<span style="opacity:.5">← oldest</span> `) +
      `· ` +
      (i > 0 ? `<a href="#" data-nav="${files[i-1].f}">${files[i-1].f.replace(/\.md$/,"")} →</a>` : `<span style="opacity:.5">newest →</span>`) +
      ` · <a href="#" id="copy-md">⧉ copy md</a>` +
      `</p>`;
    $("doc").innerHTML = nav + mdRender(md);
    document.title = `${f.replace(/\.md$/,"")} — trendscope digest`;
  }
  $("doc").addEventListener("click", e => {
    if (e.target?.id === "copy-md") {
      e.preventDefault();
      const a = e.target;
      navigator.clipboard?.writeText(lastMd).then(() => { a.textContent = "✓ copied"; setTimeout(() => a.textContent = "⧉ copy md", 1500); });
      return;
    }
    const f = e.target?.dataset?.nav; if (!f) return;
    e.preventDefault();
    show(f).catch(() => {}); scrollTo({top: 0});
  });
  $("files").onclick = e => { const f = e.target?.dataset?.f; if (f) show(f).catch(() => { $("doc").innerHTML = '<p id="err">failed to load</p>'; }); };
  document.addEventListener("keydown", e => {
    if (e.target.matches("input,textarea")) return;
    const i = files.findIndex(e2 => e2.f === cur);
    const t = e.key === "ArrowLeft" && i < files.length - 1 ? files[i + 1].f
            : e.key === "ArrowRight" && i > 0 ? files[i - 1].f : null;
    if (t) show(t).catch(() => {}), scrollTo({top: 0});
  });
  await show(wanted).catch(() => { $("doc").innerHTML = '<p id="err">failed to load digest</p>'; });
}
const briefs = idx.briefs || [];
if (briefs.length) {
  $("movers").insertAdjacentHTML("afterend",
    `<p class="movers-note">Daily brief: ` +
    briefs.slice(0, 5).map(d2 => `<a href="https://github.com/zalize-com/trendscope/blob/main/docs/brief/${d2}.md">${d2}</a>`).join(" · ") +
    `</p>`);
}
const movers = idx.movers || [];
if (movers.length) {
  const latest = movers[0];
  $("movers").innerHTML =
    `Daily movers: ` +
    (movers[1] ? `<a href="compare.html?a=${movers[1]}&b=${latest}">what changed on ${latest}</a> · `
               : `<a href="https://github.com/zalize-com/trendscope/blob/main/docs/movers/${latest}.md">what changed on ${latest}</a> · `) +
    movers.slice(0, 5).map(d => `<a href="https://github.com/zalize-com/trendscope/blob/main/docs/movers/${d}.md">${d}</a>`).join(" · ");
}
const analysis = idx.analysis || [];
if (analysis.length) {
  $("analysis").innerHTML = "Analysis: " + analysis.map(f =>
    `<a href="#" data-f="${f}">${f.replace(/-analysis\.md$/, "")}</a>`).join(" · ");
  $("analysis").onclick = async e => {
    const f = e.target?.dataset?.f; if (!f) return;
    e.preventDefault();
    const md = await fetch(`docs/${f}`, {cache:"no-cache"}).then(r => r.text());
    $("doc").innerHTML = mdRender(md);
    document.title = `${f.replace(/\.md$/,"")} — trendscope`;
    scrollTo({top: $("files").offsetTop});
  };
}
